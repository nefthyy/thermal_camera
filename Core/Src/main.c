/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C3_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_Delay(80);
  if (HAL_I2C_IsDeviceReady(&hi2c3, MLX90640_ADDR << 1, 3, 100) != HAL_OK)
    printf("\r\nMLX90640 not found at 0x%02X (I2C err 0x%lX)\r\n", MLX90640_ADDR, HAL_I2C_GetError(&hi2c3));
  else
    printf("\r\nMLX90640 found at 0x%02X\r\n", MLX90640_ADDR);
  status = MLX90640_SetRefreshRate(MLX90640_ADDR, RefreshRate);
  if (status != 0) printf("SetRefreshRate error: %d\r\n", status);
  status = MLX90640_SetChessMode(MLX90640_ADDR);
  if (status != 0) printf("SetChessMode error: %d\r\n", status);
  uint16_t ctrl;
  if (MLX9064x_I2CRead(MLX90640_ADDR, 0x800D, 1, &ctrl) == 0)
  {
    printf("Control register: 0x%04X\r\n", ctrl);
    // subpage mode on (bit 0), subpage repeat off (bit 3) so subpages 0 and 1 alternate
    uint16_t want = (ctrl | 0x0001) & ~0x0008;
    if (want != ctrl) MLX9064x_I2CWrite(MLX90640_ADDR, 0x800D, want);
  }
  static paramsMLX90640 mlx90640;
  status = MLX90640_DumpEE(MLX90640_ADDR, eeMLX90640);
  if (status != 0) printf("\r\nload system parameters error with code:%d\r\n",status);
  status = MLX90640_ExtractParameters(eeMLX90640, &mlx90640);
  if (status != 0) printf("\r\nParameter extraction failed with error code:%d\r\n",status);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    // read subpages until both halves of the chessboard are filled in
    int ok = 1, got = 0, tries = 0;
    float Ta = 0;
    while (got != 0x3 && tries++ < 4)
    {
        int sp = MLX90640_GetFrameData(MLX90640_ADDR, frame);
        if (sp < 0) { printf("GetFrameData error: %d\r\n", sp); ok = 0; break; }
        Ta = MLX90640_GetTa(frame, &mlx90640);
        MLX90640_CalculateTo(frame, &mlx90640, emissivity, Ta - TA_SHIFT, mlx90640To);
        got |= 1 << sp;
    }
    if (ok && got != 0x3)
    {
        printf("Only got subpage mask %d (ctrl 0x%04X)\r\n", got, frame[832]);
        ok = 0;
    }

    // sanity check about once a second: Ta should be near room temp, Vdd near 3300 mV
    static int nFrames = 0;
    if (ok && ++nFrames % 4 == 0)
        printf("Ta=%d C  Vdd=%d mV\r\n", (int)Ta, (int)(MLX90640_GetVdd(frame, &mlx90640) * 1000));

    // only send complete frames (both subpages read successfully)
    if (ok)
    {
        HAL_UART_Transmit(&huart2, (uint8_t *)"FRAME", 5, HAL_MAX_DELAY);
        HAL_UART_Transmit(&huart2, (uint8_t *)mlx90640To, sizeof(mlx90640To), HAL_MAX_DELAY);
    }



		
  }
  /* USER CODE END 3 */
}

